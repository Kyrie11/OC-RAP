def _metric_float(frame: dict[str, Any], key: str) -> float | None:
    try:
        value = float((frame.get("metrics", {}) or {}).get(key))
        return value if math.isfinite(value) else None
    except Exception:
        return None


def _scene_metric(scene: dict[str, Any], *keys: str) -> float | None:
    summary = scene.get("metric_summary", {}) or {}
    for key in keys:
        for source in (scene, summary):
            try:
                if key in source:
                    value = float(source[key])
                    if math.isfinite(value):
                        return value
            except Exception:
                pass
    return None


def _frame(trace: list[dict[str, Any]], index: int) -> dict[str, Any]:
    return trace[min(max(index, 0), len(trace) - 1)]


def _sdc_agent(frame: dict[str, Any]) -> dict[str, Any] | None:
    for agent in frame.get("agents", []):
        if agent.get("is_sdc"):
            return agent
    return None


def _sdc(frame: dict[str, Any]) -> tuple[float, float] | None:
    agent = _sdc_agent(frame)
    if agent is None:
        return None
    try:
        return float(agent["x"]), float(agent["y"])
    except Exception:
        return None


def _box_corners(agent: dict[str, Any]) -> list[tuple[float, float]]:
    x = float(agent["x"]); y = float(agent["y"])
    half_l = max(float(agent["length"]), 0.1) / 2.0
    half_w = max(float(agent["width"]), 0.1) / 2.0
    yaw = float(agent["yaw"])
    c, s = math.cos(yaw), math.sin(yaw)
    out = []
    for dx, dy in ((half_l, half_w), (half_l, -half_w), (-half_l, -half_w), (-half_l, half_w)):
        out.append((x + c * dx - s * dy, y + s * dx + c * dy))
    return out


def _orient(a, b, c) -> float:
    return (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])


def _point_segment_distance(p, a, b) -> float:
    vx, vy = b[0] - a[0], b[1] - a[1]
    wx, wy = p[0] - a[0], p[1] - a[1]
    denom = vx * vx + vy * vy
    if denom <= 1e-12:
        return math.hypot(wx, wy)
    t = max(0.0, min(1.0, (wx * vx + wy * vy) / denom))
    qx, qy = a[0] + t * vx, a[1] + t * vy
    return math.hypot(p[0] - qx, p[1] - qy)


def _segments_intersect(a, b, c, d) -> bool:
    eps = 1e-9
    o1, o2, o3, o4 = _orient(a, b, c), _orient(a, b, d), _orient(c, d, a), _orient(c, d, b)
    if ((o1 > eps and o2 < -eps) or (o1 < -eps and o2 > eps)) and ((o3 > eps and o4 < -eps) or (o3 < -eps and o4 > eps)):
        return True
    def on(p, q, r):
        return abs(_orient(p, q, r)) <= eps and min(p[0], q[0]) - eps <= r[0] <= max(p[0], q[0]) + eps and min(p[1], q[1]) - eps <= r[1] <= max(p[1], q[1]) + eps
    return on(a, b, c) or on(a, b, d) or on(c, d, a) or on(c, d, b)


def _polygon_distance(poly_a, poly_b) -> float:
    edges_a = list(zip(poly_a, poly_a[1:] + poly_a[:1]))
    edges_b = list(zip(poly_b, poly_b[1:] + poly_b[:1]))
    if any(_segments_intersect(a, b, c, d) for a, b in edges_a for c, d in edges_b):
        return 0.0
    return min(
        min(_point_segment_distance(p, c, d) for p in poly_a for c, d in edges_b),
        min(_point_segment_distance(p, a, b) for p in poly_b for a, b in edges_a),
    )


def _minimum_box_pair(frame: dict[str, Any]) -> tuple[dict[str, Any], dict[str, Any], float] | None:
    sdc = _sdc_agent(frame)
    if sdc is None:
        return None
    try:
        sdc_poly = _box_corners(sdc)
    except Exception:
        return None
    rows = []
    for other in frame.get("agents", []):
        if other.get("is_sdc"):
            continue
        try:
            dist = _polygon_distance(sdc_poly, _box_corners(other))
        except Exception:
            continue
        rows.append((dist, other))
    if not rows:
        return None
    dist, other = min(rows, key=lambda row: row[0])
    return sdc, other, float(dist)


def _prepare_roadgraph_segments(context, center, radius):
    """Prepare the exact visible road polylines once for a fixed camera.

    Rendering previously created one Line2D artist per polyline on every frame.
    A single LineCollection preserves the same geometry/linewidth/alpha while
    avoiding hundreds of Python artist constructions per frame.
    """
    cx, cy = center
    segments = []
    for polyline in (context or {}).get("roadgraph_polylines", []):
        xy = polyline.get("xy") or []
        points = []
        for point in xy:
            try:
                x, y = float(point[0]), float(point[1])
            except Exception:
                continue
            if abs(x - cx) <= radius + 5.0 and abs(y - cy) <= radius + 5.0:
                points.append((x, y))
        if len(points) >= 2:
            segments.append(points)
    return segments


def _draw_roadgraph(ax, context, center, radius, prepared_segments=None):
    segments = prepared_segments
    if segments is None:
        segments = _prepare_roadgraph_segments(context, center, radius)
    if segments:
        cycle = plt.rcParams.get("axes.prop_cycle").by_key().get("color", ["C0"])
        colors = [cycle[i % len(cycle)] for i in range(len(segments))]
        ax.add_collection(LineCollection(segments, colors=colors, linewidths=0.65, alpha=0.35, zorder=0))


def _all_model_fixed_view(traces: dict[str, list[dict[str, Any]]], minimum_radius: float):
    points = [point for trace in traces.values() for frame in trace for point in [_sdc(frame)] if point is not None]
    if not points:
        return (0.0, 0.0), minimum_radius
    min_x, max_x = min(p[0] for p in points), max(p[0] for p in points)
    min_y, max_y = min(p[1] for p in points), max(p[1] for p in points)
    center = ((min_x + max_x) / 2.0, (min_y + max_y) / 2.0)
    radius = max(minimum_radius, 0.55 * max(max_x - min_x, max_y - min_y) + 6.0)
    return center, radius


def _dynamic_center(traces: list[list[dict[str, Any]]], sim_index: int):
    points = [p for trace in traces for p in [_sdc(_frame(trace, sim_index))] if p is not None]
    if not points:
        return 0.0, 0.0
    return sum(x for x, _ in points) / len(points), sum(y for _, y in points) / len(points)


def _contact_marker(trace, regime):
    for idx, row in enumerate(trace):
        if (_metric_float(row, "overlap") or 0.0) > 0.5:
            return _sdc(row), "observed overlap", idx
    # Contact bucket membership is a counterfactual-surrogate label in the
    # current dataset build, not proof that raw WOMD replay starts post-impact.
    # Do not draw a fabricated contact marker when no simulator overlap occurs.
    return None, None, None


def _yaw_rate(trace: list[dict[str, Any]], index: int, metric_dt_s: float) -> float | None:
    if index <= 0:
        return 0.0
    curr = _metric_float(_frame(trace, index), "ego_yaw_rad")
    prev = _metric_float(_frame(trace, index - 1), "ego_yaw_rad")
    if curr is None or prev is None:
        return None
    return math.atan2(math.sin(curr - prev), math.cos(curr - prev)) / metric_dt_s


def _draw_frame(
    ax, trace, sim_index, title, center, radius, contact_xy, contact_label, metric_dt_s, context=None, contact_event_index=None,
    *, show_hud: bool = True, show_axes: bool = True, show_clearance_annotation: bool = True,
    roadgraph_segments=None,
):
    held = sim_index >= len(trace)
    row = _frame(trace, sim_index)
    cx, cy = center
    ax.clear(); ax.set_aspect("equal", adjustable="box")
    ax.set_xlim(cx - radius, cx + radius); ax.set_ylim(cy - radius, cy + radius)
    _draw_roadgraph(ax, context, center, radius, prepared_segments=roadgraph_segments)
    ax.set_title(title + (" · final state held" if held else ""), fontsize=10)
    if show_axes:
        ax.set_xlabel("x [m]"); ax.set_ylabel("y [m]"); ax.grid(alpha=0.15)
    else:
        ax.set_xticks([]); ax.set_yticks([]); ax.grid(False)

    trail = [_sdc(r) for r in trace[:min(sim_index, len(trace) - 1) + 1]]
    trail = [p for p in trail if p is not None]
    if len(trail) >= 2:
        ax.plot([p[0] for p in trail], [p[1] for p in trail], linewidth=1.8, alpha=0.9, zorder=2)
    # Never leak a future collision into earlier frames. The marker only appears
    # once the event has actually happened; its text label is restricted to the
    # event neighborhood to avoid covering vehicles for the rest of the clip.
    if contact_xy is not None and contact_event_index is not None and sim_index >= contact_event_index:
        ax.scatter([contact_xy[0]], [contact_xy[1]], marker="x", s=70, linewidths=1.8, alpha=0.75, zorder=5)
        if abs(sim_index - contact_event_index) <= 1:
            ax.annotate(contact_label or "contact", contact_xy, xytext=(6, 6), textcoords="offset points", fontsize=7,
                        bbox={"boxstyle": "round", "facecolor": "white", "alpha": 0.75}, zorder=7)

    overlap = (_metric_float(row, "overlap") or 0.0) > 0.5
    offroad = (_metric_float(row, "offroad") or 0.0) > 0.5
    for agent in row.get("agents", []):
        try:
            x, y = float(agent["x"]), float(agent["y"])
            length, width, yaw = max(float(agent["length"]), 0.1), max(float(agent["width"]), 0.1), float(agent["yaw"])
        except Exception:
            continue
        if abs(x - cx) > radius + length or abs(y - cy) > radius + length:
            continue
        is_sdc = bool(agent.get("is_sdc"))
        edge = "red" if is_sdc and overlap else ("orange" if is_sdc and offroad else ("tab:blue" if is_sdc else "0.35"))
        rect = patches.Rectangle((x - length / 2, y - width / 2), length, width, fill=False,
                                 linewidth=2.4 if is_sdc else 0.8, edgecolor=edge, zorder=4 if is_sdc else 3)
        rect.set_transform(transforms.Affine2D().rotate_around(x, y, yaw) + ax.transData)
        ax.add_patch(rect)
        if is_sdc:
            ax.text(x, y, "SDC", fontsize=8, ha="center", va="center", zorder=6)

    reported = _metric_float(row, "min_clearance_m")
    pair = _minimum_box_pair(row)
    if show_clearance_annotation and pair is not None and reported is not None:
        sdc, other, rendered_dist = pair
        sx, sy, ox, oy = float(sdc["x"]), float(sdc["y"]), float(other["x"]), float(other["y"])
        ax.plot([sx, ox], [sy, oy], linestyle="--", linewidth=1.0, alpha=0.65, zorder=1)
        mismatch = abs(rendered_dist - max(0.0, reported)) > 0.15
        label = f"clearance={reported:.2f} m"
        if mismatch:
            label += "*"
        ax.annotate(label, ((sx + ox) / 2.0, (sy + oy) / 2.0), xytext=(4, 4), textcoords="offset points", fontsize=7,
                    bbox={"boxstyle": "round", "facecolor": "white", "alpha": 0.70}, zorder=7)

    # Keep the map readable. Detailed candidate/reason/provenance belongs in
    # the side panel/index, not on top of road geometry.
    status = [f"t={row.get('time_index')}"]
    for key, label, unit in (("min_clearance_m", "clr", "m"), ("ttc_s", "TTC", "s"),
                             ("ego_speed_mps", "v", "m/s")):
        value = _metric_float(row, key)
        if value is not None:
            status.append(f"{label}={value:.2f}{unit}")
    flags = []
    if overlap:
        flags.append("OVERLAP")
    if offroad:
        flags.append("OFF-ROAD")
    yr = _yaw_rate(trace, min(sim_index, len(trace) - 1), metric_dt_s)
    if yr is not None:
        status.append(f"yaw-rate={yr:.2f}rad/s")
    lines = ["  ·  ".join(status[:4])]
    if flags:
        lines.append(" / ".join(flags))
    if show_hud:
        ax.text(0.012, 0.985, "\n".join(lines), transform=ax.transAxes, va="top", fontsize=7.8,
                bbox={"boxstyle": "round,pad=0.25", "facecolor": "white", "alpha": 0.78}, zorder=10)


def _sample_indices(
    frame_count: int, fps: int, metric_dt_s: float, playback_slowdown: float = 1.0,
    *, clip_duration_s: float | None = None, max_sim_index: int | None = None,
) -> list[int]:
    """Map encoded frames onto simulation states, including the clip endpoint.

    The old time-based formula sampled frame i at i/fps and therefore a 4.0 s
    clip encoded at 10 fps ended at 3.9 s.  For Contact supplements this could
    omit the terminal render state while the side panel correctly reported the
    full-run terminal metric.  When clip_duration_s is supplied, distribute the
    encoded frames over [0, terminal_index] inclusively so the final video frame
    and terminal metric refer to the same simulated endpoint.
    """
    playback_slowdown = float(playback_slowdown)
    if not math.isfinite(playback_slowdown) or playback_slowdown <= 0.0:
        raise ValueError(f"invalid playback_slowdown={playback_slowdown}")
    if frame_count <= 1:
        return [0]
    if clip_duration_s is None:
        indices = [int(round((i / fps / playback_slowdown) / metric_dt_s)) for i in range(frame_count)]
    else:
        terminal = max(0, int(round(float(clip_duration_s) / float(metric_dt_s))))
        if max_sim_index is not None:
            terminal = min(terminal, max(0, int(max_sim_index)))
        indices = [int(round(i * terminal / (frame_count - 1))) for i in range(frame_count)]
    if max_sim_index is not None:
        cap = max(0, int(max_sim_index))
        indices = [min(max(0, x), cap) for x in indices]
    return indices


def _validate_trace_time_alignment(traces: dict[str, list[dict[str, Any]]], item: dict[str, Any]) -> dict[str, Any]:
    starts: dict[str, int] = {}
    lengths: dict[str, int] = {}
    for method, trace in traces.items():
        times = []
        for row in trace:
            try:
                times.append(int(row["time_index"]))
            except Exception as exc:
                raise SystemExit(f"{item.get('target_key')}: render_trace for {method} lacks integer time_index") from exc
        if not times:
            raise SystemExit(f"{item.get('target_key')}: empty time-index sequence for {method}")
        bad = [(a, b) for a, b in zip(times, times[1:]) if b != a + 1]
        if bad:
            raise SystemExit(f"{item.get('target_key')}: non-consecutive render time_index for {method}; examples={bad[:5]}")
        starts[method] = times[0]
        lengths[method] = len(times)
    if len(set(starts.values())) != 1:
        raise SystemExit(f"{item.get('target_key')}: model traces do not start at the same simulator time: {starts}")
    # Safe/Near treatment starts at the locked target.  Contact first executes
    # the shared exact-a0 pre-treatment prelude, so the compared policies and
    # render traces start at the observed-contact treatment boundary instead.
    expected_field = "contact_anchor_time_index" if item.get("contact_anchor_time_index") is not None else "target_time_index"
    expected = item.get(expected_field)
    if expected is not None and int(expected) != next(iter(starts.values())):
        raise SystemExit(
            f"{item.get('target_key')}: trace start time {next(iter(starts.values()))} != selected {expected_field} {expected}"
        )
    return {
        "start_time_index": next(iter(starts.values())),
        "expected_start_field": expected_field,
        "expected_start_time_index": int(expected) if expected is not None else None,
        "trace_lengths": lengths,
        "consecutive": True,
    }


def _series(trace: list[dict[str, Any]], key: str, sim_indices: list[int]) -> list[float]:
    values = []
    for idx in sim_indices:
        val = _metric_float(_frame(trace, idx), key)
        values.append(float("nan") if val is None else val)
    return values


def _prepare_timeline_cache(traces: dict[str, list[dict[str, Any]]], sim_indices: list[int], regime: str):
    secondary_key = "ttc_s" if regime == "near" else "ego_speed_mps"
    out = {}
    for method, trace in traces.items():
        out[method] = {
            "clearance": _series(trace, "min_clearance_m", sim_indices),
            "secondary": _series(trace, secondary_key, sim_indices),
            "overlap": [((_metric_float(_frame(trace, idx), "overlap") or 0.0) > 0.5) for idx in sim_indices],
        }
    return out


def _draw_timeline(ax, twin, traces: dict[str, list[dict[str, Any]]], display: dict[str, str], frame_index: int,
                   sim_indices: list[int], fps: int, regime: str, series_cache=None, playback_slowdown: float = 1.0):
    ax.clear(); twin.clear()
    times = [i / fps for i in range(len(sim_indices))]
    visible = min(frame_index + 1, len(times))
    cache = series_cache or _prepare_timeline_cache(traces, sim_indices, regime)
    for method in traces:
        ax.plot(times[:visible], cache[method]["clearance"][:visible], label=f"{display[method]} clearance")
    if regime == "near":
        ax.axhline(2.0, linestyle="--", linewidth=0.9, alpha=0.6, label="2 m near-contact boundary")
    ax.set_xlim(0.0, max(times[-1] if times else 0.0, 0.1))
    xlabel = "rollout video time [s]"
    if abs(float(playback_slowdown) - 1.0) > 1e-9:
        xlabel += f" (playback {1.0/float(playback_slowdown):.2f}× real-time)"
    ax.set_xlabel(xlabel)
    ax.set_ylabel("box clearance [m]"); ax.grid(alpha=0.15)
    if regime == "contact":
        ax.axhline(0.0, linestyle="--", linewidth=0.9, alpha=0.55, label="contact boundary")
    if visible > 0:
        ax.axvline(times[visible - 1], linewidth=0.8, alpha=0.35)

    secondary_label = "TTC [s]" if regime == "near" else "ego speed [m/s]"
    for method in traces:
        twin.plot(times[:visible], cache[method]["secondary"][:visible], linestyle=":" if regime == "near" else "--",
                  alpha=0.65, label=f"{display[method]} {'TTC' if regime == 'near' else 'speed'}")
    if regime == "near":
        twin.axhline(3.0, linestyle=":", linewidth=0.9, alpha=0.45, label="3 s TTC boundary")
    twin.yaxis.set_label_position("right")
    twin.yaxis.tick_right()
    twin.set_ylabel(secondary_label, labelpad=10)

    overlap_y = ax.get_ylim()[0]
    for method in traces:
        xs = [times[j] for j in range(visible) if cache[method]["overlap"][j]]
        if xs:
            ax.scatter(xs, [overlap_y] * len(xs), marker="x", s=18, label=f"{display[method]} overlap")
    handles, labels = ax.get_legend_handles_labels(); h2, l2 = twin.get_legend_handles_labels()
    ax.legend(handles + h2, labels + l2, loc="upper right", fontsize=6.7, ncol=2)


def _fmt(value: float | None, unit: str = "", digits: int = 2) -> str:
    return "n/a" if value is None else f"{value:.{digits}f}{unit}"


