def _short_display(method: str, max_len: int = 28) -> str:
    text = _display_name(method)
    return text if len(text) <= max_len else text[: max_len - 1] + "…"


def _fmt_panel(value: Any, unit: str, digits: int) -> str:
    try:
        x = float(value)
    except Exception:
        return "n/a"
    if not math.isfinite(x):
        return "n/a"
    return f"{x:.{digits}f}{unit}"


def _favorable_delta(ocrap: Any, external: Any, direction: str) -> float | None:
    try:
        a, b = float(ocrap), float(external)
    except Exception:
        return None
    if not math.isfinite(a) or not math.isfinite(b):
        return None
    return (a - b) if direction == "higher" else (b - a)


