#!/usr/bin/env bash
set -euo pipefail

# v48.15 PRISM-CC: low-capacity, target-domain evidence correction.
# The source top-k proposal and source ordinal-evidence experts are frozen.
# Only a zero-initialized (<1k parameter) regime-specific residual calibrator
# is trained on the dedicated adaptation split.
REPO="${OCRAP_REPO:-$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)}"
