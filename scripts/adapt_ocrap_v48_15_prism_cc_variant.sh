  "source_checkpoint": "$INIT_CKPT",
  "training_role": "low_capacity_scene_disjoint_evidence_correction",
  "frozen_policy": "v48.13_topk_recovery_proposal",
  "frozen_source_evidence": true,
  "trainable": ["direct_evidence_calibrators"],
  "calibrator_hidden": $CAL_HIDDEN,
  "calibrator_residual_scale": $CAL_SCALE,
  "proposal_top_k": $PROPOSAL_TOP_K,
  "risk_source": "ordinal_evidence",
  "test_roots_read": false
}
JSON

TRAIN_OCRAP_ROOT="${TRAIN_OCRAP_ROOT:-/data0/senzeyu2/dataset/OCRAP}" \
EVAL_OCRAP_ROOT="${EVAL_OCRAP_ROOT:-/data0/senzeyu2/dataset/OCRAP}" \
TRAIN_MIX="$TRAIN_MIX" VAL_MIX="$VAL_MIX" CAL_MIX="$VAL_MIX" \
RUN="$RUN" MODEL_DIR="$MODEL_DIR" CAL_DIR="$CAL_DIR" \
INIT_CKPT="$INIT_CKPT" VARIANT="$VARIANT" TRAIN_GPU="$TRAIN_GPU" GROUP_INDEX="$GROUP_INDEX" \
NUM_WORKERS="${NUM_WORKERS:-4}" PREFETCH_FACTOR="${PREFETCH_FACTOR:-2}" BATCH_SIZE="${BATCH_SIZE:-72}" \
EPOCHS="${EVIDENCE_ADAPT_EPOCHS:-10}" PATIENCE="${EVIDENCE_ADAPT_PATIENCE:-4}" \
LR="${EVIDENCE_ADAPT_LR:-0.00020}" ENCODER_LR_SCALE=0 ENCODER_ANCHOR_WEIGHT=0 \
TRAINABLE_PARAM_PREFIXES='direct_evidence_calibrators' \
